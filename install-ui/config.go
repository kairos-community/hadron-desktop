package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

// Choice is everything the wizard collects. Password is plaintext and is never
// written anywhere — only its hash reaches disk.
type Choice struct {
	Hostname string
	Username string
	Password string
	Github   string
	Disk     string

	// KeyboardLayout and KeyboardVariant are XKB names ("de", "nodeadkeys").
	// ConsoleKeymap is the matching kbd keymap for the text console, or ""
	// when there is none. Timezone is an IANA name ("Europe/Rome").
	KeyboardLayout  string
	KeyboardVariant string
	ConsoleKeymap   string
	Timezone        string

	// Encrypt asks kairos-agent to encrypt COS_PERSISTENT with Passphrase,
	// which the machine then asks for at every boot. The passphrase is never
	// in the cloud-config: it reaches kcrypt through passphraseFile.
	Encrypt    bool
	Passphrase string
}

// desktopGroups are the supplemental groups a desktop user needs: seat/input for
// logind and libinput, audio/video/render for PipeWire and DRM, bluetooth for
// BlueZ, docker for rootful docker, admin for sudo. Kept identical to the shell
// installer this replaces.
const desktopGroups = "[admin, audio, video, render, input, bluetooth, seat, docker]"

// RenderCloudConfig produces the Kairos cloud-config the installer drops in /oem
// for `kairos-agent install` to merge. hash is a crypt(3) SHA-512 string.
//
// The ly save.ini stage preseeds the login screen with this user and selects the
// desktop session, so first boot lands on a filled-in login rather than an empty
// one. session_index 2 matches the session ordering in the image.
func RenderCloudConfig(c Choice, hash string) string {
	var b strings.Builder
	b.WriteString("#cloud-config\n")
	b.WriteString("# Generated by the Hadron Desktop installer.\n")
	b.WriteString("install:\n")
	fmt.Fprintf(&b, "  device: %q\n", c.Disk)
	b.WriteString("  auto: true\n")
	if c.Encrypt {
		// The installer deletes the passphrase file and checks the disk
		// before it reboots; a kairos-agent reboot would come first.
		b.WriteString("  reboot: false\n")
		b.WriteString("  encrypted_partitions:\n")
		fmt.Fprintf(&b, "    - %s\n", encryptedPartition)
		// kcrypt's passphrase method (kairos-io/kairos#6022). The path is
		// not a secret; the file it names is gone before the reboot.
		b.WriteString("kcrypt:\n")
		fmt.Fprintf(&b, "  method: %s\n", kcryptPassphraseMethod)
		fmt.Fprintf(&b, "  passphrase_file: %s\n", passphraseFile)
	} else {
		b.WriteString("  reboot: true\n")
	}
	fmt.Fprintf(&b, "hostname: %q\n", c.Hostname)
	b.WriteString("users:\n")
	fmt.Fprintf(&b, "  - name: %q\n", c.Username)
	// The name graphical login screens (cosmic-greeter) show. Kairos' users
	// schema has no gecos field, but it does not reject unknown keys, and
	// kairos-agent copies the whole config to /oem. yip reads this file as
	// cloud-init, whose users do have gecos, so the user is created with this
	// name instead of mudler/entities' default "Created by entities".
	fmt.Fprintf(&b, "    gecos: %q\n", c.Username)
	fmt.Fprintf(&b, "    passwd: '%s'\n", hash)
	fmt.Fprintf(&b, "    groups: %s\n", desktopGroups)
	if c.Github != "" {
		b.WriteString("    ssh_authorized_keys:\n")
		fmt.Fprintf(&b, "      - github:%s\n", c.Github)
	}
	b.WriteString("stages:\n")
	b.WriteString("  initramfs:\n")
	b.WriteString("    - name: \"Hadron desktop default session\"\n")
	b.WriteString("      files:\n")
	b.WriteString("        - path: /etc/ly/save.ini\n")
	b.WriteString("          permissions: 0644\n")
	b.WriteString("          content: |\n")
	fmt.Fprintf(&b, "            user = %s\n", c.Username)
	b.WriteString("            session_index = 2\n")
	writeLocaleStage(&b, c)
	if c.Encrypt {
		writeEncryptionMarker(&b)
	}
	// The display name again, in case a kairos-agent stops passing gecos
	// through. /etc is rebuilt from cloud-config at every boot, so it is set
	// again each boot, after the users step above (yip runs the users of a
	// cloud-init file first in its boot stage).
	b.WriteString("  boot:\n")
	b.WriteString("    - name: \"Hadron desktop display name\"\n")
	b.WriteString("      commands:\n")
	fmt.Fprintf(&b, "        - usermod -c %s %s\n", c.Username, c.Username)
	return b.String()
}

// writeEncryptionMarker records, with no secret, that the disk is encrypted
// with a passphrase. Like the keyboard file it is written again at every
// boot, because /etc is rebuilt from the image.
func writeEncryptionMarker(b *strings.Builder) {
	b.WriteString("    - name: \"Hadron disk encryption marker\"\n")
	b.WriteString("      files:\n")
	fmt.Fprintf(b, "        - path: %s\n", encryptionMarker)
	b.WriteString("          permissions: 0644\n")
	b.WriteString("          content: |\n")
	b.WriteString("            mode=passphrase\n")
}

// keyboardFile is the one place the installed system keeps the keyboard
// layout. /etc/profile.d/hadron-keyboard.sh exports it as XKB_DEFAULT_LAYOUT
// and XKB_DEFAULT_VARIANT, which sway, niri and cosmic-comp give to
// libxkbcommon when their own configuration names no layout. Hadron has no
// systemd-localed, so nothing else would tell them.
const keyboardFile = "/etc/hadron-desktop/keyboard"

// writeLocaleStage renders the keyboard layout and timezone as an initramfs
// stage. /etc is rebuilt from the image at every boot, so the files are
// written again each boot. initramfs is early enough for
// systemd-vconsole-setup (the console keymap) and for the X server and the
// desktop session, which start much later.
//
// The renderer returns no error, so a value that fails validation (the input
// steps already refuse those) is replaced by its default rather than
// written: nothing here may break out of the YAML or the shell commands.
func writeLocaleStage(b *strings.Builder, c Choice) {
	layout, variant := c.KeyboardLayout, c.KeyboardVariant
	if validateKeyboard(layout, variant) != nil {
		layout, variant = defaultLayout, ""
	}
	tz := c.Timezone
	if validateTimezone(tz) != nil {
		tz = defaultTimezone
	}
	b.WriteString("    - name: \"Hadron keyboard layout and timezone\"\n")
	b.WriteString("      files:\n")
	fmt.Fprintf(b, "        - path: %s\n", keyboardFile)
	b.WriteString("          permissions: 0644\n")
	b.WriteString("          content: |\n")
	fmt.Fprintf(b, "            XKB_LAYOUT=%s\n", layout)
	fmt.Fprintf(b, "            XKB_VARIANT=%s\n", variant)
	// The i3 variant runs an X server (XLibre), which reads its layout from
	// xorg.conf.d, not from the environment. The Wayland variants have no X
	// server that reads it; Xwayland takes the compositor's keymap.
	b.WriteString("        - path: /etc/X11/xorg.conf.d/00-keyboard.conf\n")
	b.WriteString("          permissions: 0644\n")
	b.WriteString("          content: |\n")
	b.WriteString("            # Written by the Hadron Desktop installer.\n")
	b.WriteString("            Section \"InputClass\"\n")
	b.WriteString("                Identifier \"hadron-keyboard\"\n")
	b.WriteString("                MatchIsKeyboard \"on\"\n")
	fmt.Fprintf(b, "                Option \"XkbLayout\" \"%s\"\n", layout)
	if variant != "" {
		fmt.Fprintf(b, "                Option \"XkbVariant\" \"%s\"\n", variant)
	}
	b.WriteString("            EndSection\n")
	b.WriteString("      commands:\n")
	// musl reads /etc/localtime. timedatectl makes the same link, but it
	// needs D-Bus, which the initramfs stage does not have.
	fmt.Fprintf(b, "        - %q\n", "ln -sfn /usr/share/zoneinfo/"+tz+" /etc/localtime")
	// The image's /etc/vconsole.conf sets the console FONT. Add the KEYMAP
	// to it instead of replacing the file.
	if km := c.ConsoleKeymap; km != "" && consoleKeymapName.MatchString(km) {
		fmt.Fprintf(b, "        - %q\n",
			"touch /etc/vconsole.conf && sed -i '/^KEYMAP=/d' /etc/vconsole.conf && echo 'KEYMAP="+km+"' >> /etc/vconsole.conf")
	}
}

// topLevelKey matches a `users:` or `install:` key at the start of a line,
// allowing leading whitespace — the same shape the shell installer grepped for.
var topLevelKey = regexp.MustCompile(`(?m)^[[:space:]]*(users|install):`)

// ConfigPresent reports whether oemDir already holds an install config other than
// our own output file. If so the caller skips the wizard and installs unattended,
// preserving the shell installer's behaviour for seeded/automated installs.
func ConfigPresent(oemDir, outPath string) (bool, error) {
	var found bool
	for _, pat := range []string{"*.yaml", "*.yml"} {
		matches, err := filepath.Glob(filepath.Join(oemDir, pat))
		if err != nil {
			return false, err
		}
		for _, m := range matches {
			same, err := filepath.Abs(m)
			if err != nil {
				continue
			}
			want, err := filepath.Abs(outPath)
			if err == nil && same == want {
				continue // never count our own output
			}
			data, err := os.ReadFile(m)
			if err != nil {
				continue // unreadable file is not a config we can honour
			}
			if topLevelKey.Match(data) {
				found = true
			}
		}
	}
	return found, nil
}

// HashPassword shells out to openssl for a crypt(3) SHA-512 hash.
//
// Go's stdlib has no crypt(3), and openssl is already in the image. Vendoring a
// SHA-512-crypt implementation would put unaudited crypto in the one code path
// where a mistake locks the user out of their own machine.
// A bare exit status is not a usable diagnostic here — an operator seeing
// "exit status 1" cannot tell a missing -6 flag (LibreSSL, old OpenSSL) from
// anything else, and the consequence of getting this wrong is a machine nobody
// can log into. So openssl's own stderr is attached to the returned error.
func HashPassword(plain string) (string, error) {
	cmd := exec.Command("openssl", "passwd", "-6", "-stdin")
	cmd.Stdin = strings.NewReader(plain)
	var stderr strings.Builder
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		if msg := strings.TrimSpace(stderr.String()); msg != "" {
			return "", fmt.Errorf("openssl passwd: %w: %s", err, msg)
		}
		return "", fmt.Errorf("openssl passwd: %w", err)
	}
	return strings.TrimSpace(string(out)), nil
}
