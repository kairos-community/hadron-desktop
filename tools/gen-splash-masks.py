#!/usr/bin/env python3
"""Generate splash/masks.h: the wordmark and the text faces as
run-length coded alpha masks. Nothing can shape a font this early in boot, so
the splash carries the pixels.

    python3 tools/gen-splash-masks.py > splash/masks.h

Coding (the same as the first prototype's wordmark.h), rows joined end to end:
    0x00..0x3f   that many + 1 clear pixels
    0xc0..0xff   that many - 0xbf solid pixels
    0x41..0xbe   one edge pixel, alpha = (byte - 0x40) / 127
"""
import math, sys
from PIL import Image, ImageDraw, ImageFont

import os
GUI = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "install-gui", "fonts") + "/"
URB = GUI + "Urbanist-SemiBold.ttf"
WORD, TRACKING = "isotope", 0.07          # Urbanist SemiBold (600)
WORD_XH = (21, 30, 40, 60)            # x-heights: 768p, 1080p, 1440p-1600p, 2160p
# name, file, px size at tier 1, characters
ASCII = "".join(chr(i) for i in range(32, 127)) + "\u00b7"
FACES = (("SANS",  GUI + "Inter-Medium.ttf", 14, ASCII),
         ("TITLE", GUI + "Inter-Medium.ttf", 21, ASCII),
         ("MONO",  GUI + "JetBrainsMono-Medium.ttf", 13, ASCII),
         ("CAPS",  GUI + "Inter-SemiBold.ttf", 11, " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789\u00b7"))
TIERS = (1, 1.3, 2)             # text sizes: under 900 rows, under 1500, above

def rle(im):
    px = [round(v * 127 / 255) for v in im.tobytes()]
    out, i = [], 0
    while i < len(px):
        v = px[i]
        if v in (0, 127):
            j = i
            while j < len(px) and px[j] == v and j - i < 64: j += 1
            out.append((j - i - 1) if v == 0 else (0xbf + j - i)); i = j
        else:
            out.append(0x40 + v); i += 1
    return out

def wordmark(xh, word=WORD, tracking=TRACKING):
    path = URB
    probe = ImageFont.truetype(path, 1000)
    size = xh * 1000 / -probe.getbbox("x", anchor="ls")[1]
    f = ImageFont.truetype(path, size)
    xs = [0.0]
    for i in range(1, len(word)):
        xs.append(xs[-1] + f.getlength(word[i - 1:i + 1]) - f.getlength(word[i]) + tracking * xh)
    asc, desc = math.ceil(xh * 1.75), math.ceil(xh * .6)
    im = Image.new("L", (math.ceil(xs[-1] + f.getlength(word[-1])) + 4, asc + desc), 0)
    d = ImageDraw.Draw(im)
    for ch, x in zip(word, xs):
        d.text((2 + x, asc), ch, font=f, fill=255, anchor="ls")
    box = im.getbbox(); im = im.crop(box)
    px = im.load()
    tx = next(x for x in range(im.width) if not any(px[x, y] for y in range(im.height)))
    ty = next(y for y in range(im.height) if not any(px[x, y] for x in range(tx)))
    return im, asc - box[1], tx, ty

def emit(name, data):
    print("static const unsigned char %s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 24):
        print(" " + ",".join("%d" % b for b in data[i:i + 24]) + ",")
    print("};")

def main():
    total = 0
    print("/* Generated by tools/gen_masks.py. Urbanist, Inter and JetBrains Mono are\n"
          "   under the SIL Open Font License 1.1. Run-length coded alpha masks:\n"
          "   0..63 clear run (n+1), 192..255 solid run (n-191), 65..190 one edge\n"
          "   pixel with alpha (n-64)/127. */")
    print("typedef struct { short w, h, base, tx, ty; unsigned short n; const unsigned char *d; } wordmark_t;")
    print("typedef struct { signed char xo, yo; unsigned char w, h, adv; unsigned short off, n; } glyph_t;")
    print("typedef struct { const glyph_t *g; const unsigned char *d; const char *set; short px, cap; } face_t;")
    meta = []
    for xh in WORD_XH:
        im, base, tx, ty = wordmark(xh)
        data = rle(im); total += len(data)
        emit("WM_%d" % xh, data)
        meta.append("    { %d, %d, %d, %d, %d, %d, WM_%d }," % (im.width, im.height, base, tx, ty, len(data), xh))
    print("static const wordmark_t WORDMARK[%d] = {\n%s\n};" % (len(meta), "\n".join(meta)))
    faces = []
    for name, path, px, chars in FACES:
        for t in TIERS:
            f = ImageFont.truetype(path, round(px * t))
            cap = -f.getbbox("H", anchor="ls")[1]
            data, glyphs = [], []
            for ch in chars:
                adv = round(f.getlength(ch))
                bb = f.getbbox(ch, anchor="ls")
                w, h = bb[2] - bb[0], bb[3] - bb[1]
                if w <= 0 or h <= 0 or ch == " ":
                    glyphs.append((0, 0, 0, 0, adv, len(data), 0)); continue
                im = Image.new("L", (w, h), 0)
                ImageDraw.Draw(im).text((-bb[0], -bb[1]), ch, font=f, fill=255, anchor="ls")
                r = rle(im)
                glyphs.append((bb[0], bb[1], w, h, adv, len(data), len(r)))
                data += r
            total += len(data) + len(glyphs) * 9
            tn = TIERS.index(t)
            emit("%s%d_D" % (name, tn), data)
            print("static const glyph_t %s%d_G[%d] = {" % (name, tn, len(glyphs)))
            print("\n".join("    {%d,%d,%d,%d,%d,%d,%d}," % g for g in glyphs))
            print("};")
            cs = chars.replace("\\", "\\\\").replace('"', '\\"').replace("\u00b7", "\\267")
            faces.append('    { %s%d_G, %s%d_D, "%s", %d, %d },' % (name, tn, name, tn, cs, round(px * t), cap))
            sys.stderr.write("%s x%g: %d bytes\n" % (name, t, len(data)))
    print("enum { F_SANS, F_TITLE, F_MONO, F_CAPS };")
    print("static const face_t FACE[%d] = {\n%s\n};" % (len(faces), "\n".join(faces)))
    sys.stderr.write("total about %d bytes\n" % total)

if __name__ == "__main__":
    main()
